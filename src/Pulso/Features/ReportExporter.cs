</style></head><body><h1>{{{E(title)}}}</h1><div class="stamp">{{{E(Stamp)}}}</div>
""");
        foreach (var p in pages)
        {
            sb.Append($"<h2>{E(p.Title)}</h2><div class=\"grid\">");
            foreach (var g in p.Groups)
            {
                sb.Append($"<div class=\"card\"><h3>{E(g.Title)}</h3>");
                foreach (var (lvl, text) in g.Notes) sb.Append($"<div class=\"note\">{E(text)}</div>");
                foreach (var i in g.Items)
                    sb.Append($"<div class=\"row\"><span class=\"k\"{(i.HasTip ? $" title=\"{E(i.Tip!)}\"" : "")}>{E(i.Key)}</span><span class=\"v {C(i.Status)}\">{E(i.Value)}</span></div>");
                foreach (var t in g.Tables)
                {
                    sb.Append("<table><tr>");
                    foreach (var c in t.Columns) sb.Append($"<th>{E(c)}</th>");
                    sb.Append("</tr>");
                    for (int r = 0; r < t.Rows.Count; r++)
                    {
                        sb.Append($"<tr class=\"{C(t.RowStatus[r])}\"{(t.RowTips[r] is string tip ? $" title=\"{E(tip)}\"" : "")}>");
                        foreach (var c in t.Rows[r]) sb.Append($"<td>{E(c)}</td>");
                        sb.Append("</tr>");
                    }
                    sb.Append("</table>");
                }
                sb.Append("</div>");
            }
            sb.Append("</div>");
        }
        sb.Append("</body></html>");
        return sb.ToString();
    }

    // ----------------------------------------------------------------- PDF mínimo (A4, fontes padrão)

    public static byte[] ToPdf(List<InfoPage> pages, string title)
    {
        Encoding.RegisterProvider(CodePagesEncodingProvider.Instance);
        var enc = Encoding.GetEncoding(1252, new EncoderReplacementFallback("?"), DecoderFallback.ReplacementFallback);

        // Conteúdo como linhas (fonte monoespaçada mantém as colunas das tabelas).
        var lines = new List<(string text, int kind)>(); // 0 = normal, 1 = título, 2 = seção, 3 = página
        lines.Add((title, 1));
        lines.Add((Stamp, 0));
        lines.Add(("", 0));
        const int width = 96;
        foreach (var p in pages)
        {
            lines.Add((p.Title, 3));
            foreach (var raw in p.ToText().Replace("\r", "").Split('\n').Skip(2))
            {
                int kind = raw.StartsWith("[") ? 2 : 0;
                string l = kind == 2 ? raw.Trim('[', ']') : raw;
                while (l.Length > width) { lines.Add((l[..width], kind)); l = "      " + l[width..]; }
                lines.Add((l, kind));
            }
        }

        const double pageW = 595, pageH = 842, margin = 42, lineH = 11.5;
        var pageStreams = new List<string>();
        var sb = new StringBuilder();
        double y = pageH - margin;
        void NewPage()
        {
            if (sb.Length > 0) pageStreams.Add(sb.ToString());
            sb.Clear();
            y = pageH - margin;
        }
        string Esc(string s) => s.Replace("\\", "\\\\").Replace("(", "\\(").Replace(")", "\\)");
        foreach (var (text, kind) in lines)
        {
            double h = kind switch { 1 => 24, 3 => 22, 2 => 16, _ => lineH };
            if (kind == 3 && y < pageH - margin - 10) NewPage();
            if (y - h < margin) NewPage();
            y -= h;
            string font = kind switch { 1 => "/F2 16", 3 => "/F2 13", 2 => "/F2 10", _ => "/F1 8.2" };
            sb.Append($"BT {font} Tf {margin:0.##} {y:0.##} Td ({Esc(text)}) Tj ET\n");
        }
        if (sb.Length > 0) pageStreams.Add(sb.ToString());

        var ms = new MemoryStream();
        var offsets = new List<long>();
        void W(string s) { var b = enc.GetBytes(s); ms.Write(b, 0, b.Length); }
        void Obj(string body) { offsets.Add(ms.Position); W($"{offsets.Count} 0 obj\n{body}\nendobj\n"); }

        W("%PDF-1.4\n%âãÏÓ\n");
        int n = pageStreams.Count;
        // 1 catálogo, 2 páginas, 3 fonte mono, 4 fonte negrito, depois (conteúdo, página) por página
        var kids = string.Join(" ", Enumerable.Range(0, n).Select(i => $"{6 + i * 2} 0 R"));
        Obj("<< /Type /Catalog /Pages 2 0 R >>");
        Obj($"<< /Type /Pages /Kids [{kids}] /Count {n} >>");
        Obj("<< /Type /Font /Subtype /Type1 /BaseFont /Courier /Encoding /WinAnsiEncoding >>");
        Obj("<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>");
        for (int i = 0; i < n; i++)
        {
            var bytes = enc.GetBytes(pageStreams[i]);
            offsets.Add(ms.Position);
            W($"{offsets.Count} 0 obj\n<< /Length {bytes.Length} >>\nstream\n");
            ms.Write(bytes, 0, bytes.Length);
            W("\nendstream\nendobj\n");
            Obj($"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 {pageW} {pageH}] /Resources << /Font << /F1 3 0 R /F2 4 0 R >> >> /Contents {offsets.Count} 0 R >>");
        }
        long xref = ms.Position;
        W($"xref\n0 {offsets.Count + 1}\n0000000000 65535 f \n");
        foreach (var o in offsets) W($"{o:0000000000} 00000 n \n");
        W($"trailer\n<< /Size {offsets.Count + 1} /Root 1 0 R >>\nstartxref\n{xref}\n%%EOF\n");
        return ms.ToArray();
    }
}

namespace Pulso.Features;

/// <summary>Relatórios em TXT, HTML e PDF (PDF gerado sem bibliotecas externas).</summary>
public static class ReportExporter
{
    public static async Task<List<InfoPage>> BuildAllAsync()
    {
        var pages = new List<InfoPage>();
        async Task Add(Func<Task<InfoPage>> f) { try { pages.Add(await f()); } catch (Exception ex) { Paths.LogError("Report", ex); } }
        async Task AddMany(Func<Task<List<InfoPage>>> f) { try { pages.AddRange(await f()); } catch (Exception ex) { Paths.LogError("Report", ex); } }
        await Add(InfoPages.CpuAsync);
        await AddMany(GpuInfo.BuildPagesAsync);
        await Add(MemoryInfo.BuildPageAsync);
        await AddMany(StorageInfo.BuildPagesAsync);
        await Add(InfoPages.BoardAsync);
        await Add(InfoPages.NetworkAsync);
        await Add(InfoPages.OsAsync);
        return pages;
    }

    /// <summary>Menu TXT / HTML / PDF abaixo do controle. Sem páginas = relatório completo.</summary>
    public static void ShowMenu(FrameworkElement anchor, List<InfoPage>? pages)
    {
        var menu = new ContextMenu { PlacementTarget = anchor, Placement = System.Windows.Controls.Primitives.PlacementMode.Bottom };
        foreach (var f in new[] { "TXT", "HTML", "PDF" })
        {
            string fmt = f;
            var mi = new MenuItem { Header = Loc.T($"Salvar como {fmt}", $"Save as {fmt}") };
            mi.Click += async (_, _) =>
            {
                var p = pages ?? await BuildAllAsync();
                Export(fmt, p, Loc.T("Relatório completo do sistema", "Full system report"));
            };
            menu.Items.Add(mi);
        }
        var copy = new MenuItem { Header = Loc.T("Copiar texto", "Copy text") };
        copy.Click += async (_, _) =>
        {
            var p = pages ?? await BuildAllAsync();
            try { Clipboard.SetText(ToText(p, Loc.T("Relatório do sistema", "System report"))); } catch { }
        };
        menu.Items.Add(copy);
        menu.IsOpen = true;
    }

    public static void Export(string fmt, List<InfoPage> pages, string title)
    {
        if (pages.Count == 0) return;
        var dlg = new SaveFileDialog
        {
            InitialDirectory = Paths.Reports,
            FileName = $"Pulso_{Environment.MachineName}_{DateTime.Now:yyyy-MM-dd_HHmm}",
            DefaultExt = fmt.ToLowerInvariant(),
            Filter = fmt switch { "HTML" => "HTML (*.html)|*.html", "PDF" => "PDF (*.pdf)|*.pdf", _ => Loc.T("Texto", "Text") + " (*.txt)|*.txt" },
        };
        if (dlg.ShowDialog() != true) return;
        try
        {
            switch (fmt)
            {
                case "HTML": File.WriteAllText(dlg.FileName, ToHtml(pages, title), Encoding.UTF8); break;
                case "PDF": File.WriteAllBytes(dlg.FileName, ToPdf(pages, title)); break;
                default: File.WriteAllText(dlg.FileName, ToText(pages, title), Encoding.UTF8); break;
            }
            Process.Start(new ProcessStartInfo(dlg.FileName) { UseShellExecute = true });
        }
        catch (Exception ex)
        {
            Paths.LogError("Export", ex);
            MessageBox.Show(Loc.T("Não foi possível salvar o relatório: ", "Could not save the report: ") + ex.Message, "Pulso");
        }
    }

    static string Stamp => Loc.T($"Gerado pelo Pulso em {DateTime.Now:dd/MM/yyyy HH:mm} · {Environment.MachineName}",
                                 $"Generated by Pulso on {DateTime.Now:yyyy-MM-dd HH:mm} · {Environment.MachineName}");

    public static string ToText(List<InfoPage> pages, string title)
    {
        var sb = new StringBuilder();
        sb.AppendLine(title);
        sb.AppendLine(Stamp);
        sb.AppendLine();
        foreach (var p in pages)
        {
            sb.AppendLine(p.ToText());
            sb.AppendLine();
        }
        return sb.ToString();
    }

    public static string ToHtml(List<InfoPage> pages, string title)
    {
        string E(string s) => WebUtility.HtmlEncode(s);
        string C(Health h) => h switch { Health.Good => "good", Health.Warning => "warn", Health.Critical => "crit", _ => "" };
        var sb = new StringBuilder();
        sb.Append($$$"""
<!doctype html><html lang="{{{(Loc.En ? "en" : "pt-BR")}}}"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>{{{E(title)}}}</title>
<style>
:root{--bg:#161918;--card:#1f2321;--tile:#262b28;--div:#2a2f2c;--text:#e8ece9;--t3:#9aa39d;--mut:#8a938d;--acc:#c5f36a;--warn:#f2b84b;--crit:#f26b5b}
@media print{:root{--bg:#fff;--card:#fff;--tile:#f2f4f1;--div:#ddd;--text:#111;--t3:#444;--mut:#666;--acc:#4a7a0c;--warn:#a86a00;--crit:#c0392b}}
*{box-sizing:border-box}body{margin:0;background:var(--bg);color:var(--text);font:14px/1.45 Manrope,'Segoe UI',system-ui,sans-serif;padding:32px}
h1{font-size:28px;margin:0 0 4px;font-weight:800}.stamp{color:var(--mut);font-size:12px;margin-bottom:24px}
h2{font-size:20px;margin:32px 0 12px;font-weight:800}.grid{display:grid;grid-template-columns:repeat(auto-fill,minmax(420px,1fr));gap:16px}
.card{background:var(--card);border-radius:16px;padding:16px 20px;break-inside:avoid}.card h3{font-size:15px;margin:0 0 8px}
.row{display:flex;justify-content:space-between;gap:16px;padding:8px 0;border-top:1px solid var(--div)}.row .k{color:var(--t3)}
.row .v{font-family:'JetBrains Mono',Consolas,monospace;font-weight:600;text-align:right}
.good{color:var(--acc)}.warn{color:var(--warn)}.crit{color:var(--crit)}
.note{background:var(--tile);border-radius:10px;padding:10px 12px;margin:6px 0;color:var(--warn)}
table{width:100%;border-collapse:collapse;font-size:13px;margin-top:6px}th{text-align:left;color:var(--acc);font-weight:600;padding:6px 8px 6px 0}
